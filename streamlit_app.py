import streamlit as st
import joblib
import numpy as np

# Load the trained ML model
model = joblib.load("student_model.pkl")

# Page configuration
st.set_page_config(
    page_title="Student Performance Prediction",
    page_icon="🎓",
    layout="centered"
)

# Title
st.title("🎓 Student Performance Prediction")
st.write("Predict student academic performance using Machine Learning.")

st.divider()

# Student details
st.header("Enter Student Details")

study_hours = st.number_input(
    "Study Hours per Day",
    min_value=0.0,
    max_value=24.0,
    value=5.0
)

attendance = st.number_input(
    "Attendance Percentage",
    min_value=0.0,
    max_value=100.0,
    value=80.0
)

previous_marks = st.number_input(
    "Previous Marks",
    min_value=0.0,
    max_value=100.0,
    value=70.0
)

assignment_marks = st.number_input(
    "Assignment Marks",
    min_value=0.0,
    max_value=100.0,
    value=75.0
)

sleep_hours = st.number_input(
    "Sleep Hours",
    min_value=0.0,
    max_value=24.0,
    value=8.0
)

# Prediction
if st.button("Predict Performance", use_container_width=True):

    input_data = np.array([[
        study_hours,
        attendance,
        previous_marks,
        assignment_marks,
        sleep_hours
    ]])

    prediction = model.predict(input_data)[0]

    prediction = max(0, min(100, prediction))
    prediction = round(prediction, 2)

    st.divider()
    st.subheader("Prediction Result")

    st.metric("Predicted Final Marks", f"{prediction}/100")

    if prediction >= 85:
        category = "Excellent"
        feedback = "Excellent performance! Keep maintaining your study habits."

    elif prediction >= 70:
        category = "Very Good"
        feedback = "Very good performance! Keep practicing and revise regularly."

    elif prediction >= 60:
        category = "Good"
        feedback = "Good performance! Focus more on difficult subjects."

    elif prediction >= 50:
        category = "Average"
        feedback = "Average performance. Try improving study consistency."

    else:
        category = "Needs Improvement"
        feedback = "Needs improvement. Make a study plan and practice regularly."

    st.success(f"Performance Category: {category}")
    st.progress(int(prediction))
    st.info(feedback)

    st.caption("This prediction is an estimate generated by a trained ML model.")
